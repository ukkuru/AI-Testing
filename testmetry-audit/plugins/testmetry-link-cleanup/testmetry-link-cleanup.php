function tmlc_norm( $url ) {
	$p = wp_parse_url( trim( $url ) );
	if ( empty( $p['host'] ) ) { return ''; }
	$host = strtolower( $p['host'] );
	if ( 0 === strpos( $host, 'www.' ) ) { $host = substr( $host, 4 ); }
	$path = isset( $p['path'] ) ? strtolower( rawurldecode( $p['path'] ) ) : '';
	return $host . rtrim( $path, '/' );
}

