add_filter( 'the_content', function ( $content ) {
	if ( false === stripos( $content, 'href=' ) ) { return $content; }
	$post   = get_post();
	$is_job = $post && preg_match( '#(software-test(ing)?-jobs|test(ing)?-jobs)#', $post->post_name );
	$di = tmlc_dead_internal(); $de = tmlc_dead_external(); $rw = tmlc_rewrite();
	return preg_replace_callback( '#<a\s([^>]*?)href=(["\'])([^"\']*)\2([^>]*)>(.*?)</a>#is', function ( $m ) use ( $di, $de, $rw, $is_job ) {
		$k = tmlc_norm( html_entity_decode( $m[3] ) );
		if ( '' === $k ) { return $m[0]; }
		if ( isset( $di[ $k ] ) ) { return $m[5]; }
		if ( ! $is_job && isset( $de[ $k ] ) ) { return $m[5]; }
		if ( isset( $rw[ $k ] ) ) { return '<a ' . $m[1] . 'href=' . $m[2] . esc_url( $rw[ $k ] ) . $m[2] . $m[4] . '>' . $m[5] . '</a>'; }
		return $m[0];
	}, $content );
}, 24 );
